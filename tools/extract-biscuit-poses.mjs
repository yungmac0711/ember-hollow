#!/usr/bin/env node
// Bakes Biscuit's pose GLBs (art/assets/dog/biscuit/biscuit-*.glb) into a tiny JS table of per-node
// local rotations/translations, so the game only ships biscuit.glb (the mesh) and blends poses by
// slerping node quaternions. Re-run from game/ when the art changes:  node tools/extract-biscuit-poses.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const SRC = new URL('../../art/assets/dog/biscuit/', import.meta.url).pathname;
const read = (f) => { const b = readFileSync(SRC + f); const n = b.readUInt32LE(12); return JSON.parse(b.slice(20, 20 + n).toString()); };
const poses = {};
for (const [name, file] of [['stand', 'biscuit.glb'], ['sit', 'biscuit-sit.glb'], ['playbow', 'biscuit-playbow.glb'], ['curled', 'biscuit-curled.glb']]) {
  const j = read(file), p = {};
  for (const n of j.nodes) {
    if (!n.name || n.name === 'Biscuit') continue;
    p[n.name] = { q: (n.rotation || [0, 0, 0, 1]).map((v) => +v.toFixed(5)), t: (n.translation || [0, 0, 0]).map((v) => +v.toFixed(5)) };
  }
  poses[name] = p;
}
writeFileSync(new URL('../src/entities/biscuit-poses.js', import.meta.url),
  `// AUTO-GENERATED by tools/extract-biscuit-poses.mjs from art/assets/dog/biscuit/*.glb — do not edit.\n// Per-node local rotation (quaternion xyzw) + translation for each authored pose.\nexport const BISCUIT_POSES = ${JSON.stringify(poses)};\n`);
console.log('poses:', Object.keys(poses).join(', '));
