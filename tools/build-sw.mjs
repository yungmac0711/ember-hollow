#!/usr/bin/env node
// Regenerates sw.js with the full precache list + a content-hash cache version.
// Run from game/ after changing any file:  node tools/build-sw.mjs
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SKIP = new Set(['tools', 'docs', 'screenshots', 'node_modules', '.git', 'sw.js', 'README.md', 'package.json', 'package-lock.json', '.gitignore', '.nojekyll']);
// M2 chunk B: low-tier LOD manifest — every assets/models/**/<name>-low.glb Art has dropped in, so the
// low tier can load it instead of <name>.glb without probing (a 404 probe would cost a request each).
const lows = [];
(function scan(dir) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) scan(p);
    else if (/-low\.glb$/i.test(name)) lows.push(relative(root, p).split('\\').join('/'));
  }
})(join(root, 'assets/models'));
writeFileSync(join(root, 'src/data/lod-manifest.js'), `// AUTO-GENERATED by tools/build-sw.mjs — low-tier LOD GLBs present under assets/models (see src/assets.js).
export const LOW_LOD = ${JSON.stringify(lows)};
`);
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    if (SKIP.has(name) || name.startsWith('.')) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (!/\.(md|txt)$/i.test(name)) files.push(relative(root, p).split('\\').join('/'));
  }
})(root);
const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(root, f)));
const version = hash.digest('hex').slice(0, 10);
const list = ['./', ...files.map((f) => './' + f)];

writeFileSync(join(root, 'sw.js'), `// AUTO-GENERATED by tools/build-sw.mjs — do not edit by hand.
// Precaches every game file so Ember Hollow runs offline once installed. Stale-while-revalidate:
// cached files load instantly and are refreshed in the background; a new VERSION drops old caches.
const VERSION = '${version}';
const CACHE = 'ember-hollow-' + VERSION;
const PRECACHE = ${JSON.stringify(list, null, 2)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE.map((u) => new Request(u, { cache: 'reload' }))) /* bypass the HTTP cache so a new version never precaches stale files */).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k.startsWith('ember-hollow-') && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  e.respondWith(caches.open(CACHE).then(async (cache) => {
    const cached = await cache.match(req, { ignoreSearch: true });
    const network = fetch(req).then((res) => {
      if (res && res.ok && res.type === 'basic') cache.put(req, res.clone());
      return res;
    }).catch(() => null);
    if (cached) { e.waitUntil(network); return cached; }
    const res = await network;
    return res || (req.mode === 'navigate' ? cache.match('./index.html') : Response.error());
  }));
});
`);
console.log(`sw.js: ${list.length} files, version ${version}`);
