#!/usr/bin/env node
// Regenerates src/companion/story-data.js from the writer's files in ../story so the game never
// drifts from the locked story docs. Run from game/:  node tools/sync-story.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const storyDir = resolve(here, '../../story');
const out = resolve(here, '../src/companion/story-data.js');

const promptMd = readFileSync(resolve(storyDir, 'companion_system_prompt.md'), 'utf8');
const companionMd = readFileSync(resolve(storyDir, 'COMPANION.md'), 'utf8');

function codeBlockAfter(md, heading) {
  const i = md.indexOf(heading);
  if (i < 0) throw new Error(`heading not found: ${heading}`);
  const m = md.slice(i).match(/```[a-z]*\n([\s\S]*?)```/);
  if (!m) throw new Error(`no code block after ${heading}`);
  return m[1].trim();
}

const systemPrompt = codeBlockAfter(promptMd, '## System Prompt');
const contextTemplate = codeBlockAfter(promptMd, '## Context Block');

const ambientStart = companionMd.indexOf('## Ambient lines');
if (ambientStart < 0) throw new Error('Ambient lines section not found');
const ambient = {};
for (const row of companionMd.slice(ambientStart).split('\n')) {
  const m = row.match(/^\|\s*([a-z_]+)\s*\|(.*)\|\s*$/);
  if (!m || m[1] === 'trigger') continue;
  const lines = [...m[2].matchAll(/"([^"]+)"/g)].map((x) => x[1]);
  if (lines.length) ambient[m[1]] = lines;
}
const total = Object.values(ambient).reduce((n, l) => n + l.length, 0);

const js = `// AUTO-GENERATED by tools/sync-story.mjs from /story — do not edit by hand.
// Source: story/companion_system_prompt.md (System Prompt, Context Block) and story/COMPANION.md (Ambient lines).
// ${Object.keys(ambient).length} triggers, ${total} ambient lines.
export const SYSTEM_PROMPT = ${JSON.stringify(systemPrompt)};

export const CONTEXT_TEMPLATE = ${JSON.stringify(contextTemplate)};

export const AMBIENT_LINES = ${JSON.stringify(ambient, null, 2)};
`;
writeFileSync(out, js);
console.log(`wrote ${out}: ${Object.keys(ambient).length} triggers, ${total} lines`);
