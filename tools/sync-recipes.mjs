#!/usr/bin/env node
// M2 chunk B: regenerates src/data/recipes.js from story/data/recipes.json (read-only; the Writer owns it).
// Only recipes — it never touches story.js (tools/sync-story.mjs pulls the M2 lore; don't run that here).
// Run from game/:  node tools/sync-recipes.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const src = JSON.parse(readFileSync(resolve(here, '../../story/data/recipes.json'), 'utf8'));
const coz = JSON.parse(readFileSync(resolve(here, '../../story/data/coziness.json'), 'utf8'));
const tiers = (coz.tiers || []).map((t) => ({ id: t.id, name: t.name, minScore: t.minScore }));
writeFileSync(resolve(here, '../src/data/recipes.js'), `// AUTO-GENERATED by tools/sync-recipes.mjs from story/data/recipes.json (+ coziness tier names) — do not edit by hand.
export const RECIPES = ${JSON.stringify(src.recipes)};
export const COZY_TIERS = ${JSON.stringify(tiers)};
`);
console.log(`recipes.js: ${src.recipes.length} recipes, ${tiers.length} coziness tiers`);
